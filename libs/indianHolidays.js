/**
 * Get Indian Holiday for a specific YYYY-MM-DD
 */
export function getIndianHoliday(dateStr) {
    if (!dateStr) return null;
    return INDIAN_HOLIDAYS_DATA[dateStr] || null;
}

/**
 * Get all Indian Holidays in a specific Month (0-indexed month)
 */
export function getIndianHolidaysForMonth(year, month) {
    const monthStr = String(month + 1).padStart(2, '0');
    const prefix = `${year}-${monthStr}`;

    const list = [];
    for (const [dateKey, holiday] of Object.entries(INDIAN_HOLIDAYS_DATA)) {
        if (dateKey.startsWith(prefix)) {
            list.push({ date: dateKey, ...holiday });
        }
    }
    return list;
}
